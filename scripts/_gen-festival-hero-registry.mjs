#!/usr/bin/env node
/**
 * Generates apps/web/src/lib/festival-heroes.ts — the static registry of
 * festival page-slugs that have a B-roll hero clip uploaded to R2. Built by
 * intersecting the live festival page-slug set (buildFestivalSlugMap over the
 * festivals table) with the actual keys in the nakshiq-videos bucket, so the
 * registry can NEVER list a slug whose <video> would 404.
 *
 * Re-run after adding festivals + uploading new clips:
 *   node scripts/_gen-festival-hero-registry.mjs
 */
import { S3Client, ListObjectsV2Command } from "@aws-sdk/client-s3";
import { createClient } from "@supabase/supabase-js";
import { writeFileSync } from "fs";

// Run with: node --env-file=apps/web/.env.local scripts/_gen-festival-hero-registry.mjs
const env = process.env;

// --- festival page-slug set (mirror of lib/festival-slug.ts) ---
function baseSlug(name) {
  return name.toLowerCase().replace(/[^a-z0-9\s-]+/g, "").trim().replace(/\s+/g, "-").replace(/-+/g, "-");
}
function buildFestivalSlugMap(rows) {
  const baseToCount = new Map();
  for (const r of rows) {
    const b = baseSlug(r.name);
    baseToCount.set(b, (baseToCount.get(b) ?? 0) + 1);
  }
  const idToSlug = new Map();
  for (const r of rows) {
    const b = baseSlug(r.name);
    const slug = (baseToCount.get(b) ?? 1) > 1 && r.destination_id ? `${b}-${r.destination_id}` : b;
    idToSlug.set(r.id, slug);
  }
  return idToSlug;
}

const supabase = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_ANON_KEY);
const { data: rows, error } = await supabase.from("festivals").select("id, name, destination_id");
if (error) { console.error(error); process.exit(1); }
const slugMap = buildFestivalSlugMap(rows);
const pageSlugs = new Set(slugMap.values());
console.log(`Festival page-slugs: ${pageSlugs.size} (from ${rows.length} festival rows)`);

// --- R2 keys ---
const client = new S3Client({
  region: "auto",
  endpoint: `https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
  credentials: { accessKeyId: env.R2_ACCESS_KEY_ID, secretAccessKey: env.R2_SECRET_ACCESS_KEY },
});
const keys = new Set();
let token;
do {
  const r = await client.send(new ListObjectsV2Command({ Bucket: "nakshiq-videos", ContinuationToken: token }));
  for (const o of r.Contents || []) keys.add(o.Key);
  token = r.IsTruncated ? r.NextContinuationToken : undefined;
} while (token);

// --- intersection ---
const withHero = [...pageSlugs].filter((s) => keys.has(`${s}.mp4`)).sort();
console.log(`Festival slugs with a hero clip in R2: ${withHero.length}/${pageSlugs.size}`);

const lines = withHero.map((s) => `  ${JSON.stringify(s)},`).join("\n");
const out = `import { videoSrc } from "./video-url";

/**
 * Registry of /festivals/[festivalSlug] slugs that have a B-roll hero clip
 * uploaded to the nakshiq-videos R2 bucket as {slug}.mp4.
 *
 * AUTO-GENERATED by scripts/_gen-festival-hero-registry.mjs — do not edit by
 * hand. It is the intersection of the live festival page-slug set with the
 * actual R2 keys, so every entry is guaranteed to resolve. Re-run the
 * generator after adding festivals + uploading clips.
 */
export const FESTIVAL_HEROES = new Set<string>([
${lines}
]);

export const hasFestivalHero = (slug: string) => FESTIVAL_HEROES.has(slug);

/** R2 hero-clip URL for a festival slug, or "" when none exists. */
export function festivalHeroSrc(slug: string): string {
  return FESTIVAL_HEROES.has(slug) ? videoSrc(slug) : "";
}
`;

writeFileSync("apps/web/src/lib/festival-heroes.ts", out);
console.log(`Wrote apps/web/src/lib/festival-heroes.ts (${withHero.length} slugs)`);
