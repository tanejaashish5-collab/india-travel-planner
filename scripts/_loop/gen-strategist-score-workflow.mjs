#!/usr/bin/env node
/**
 * gen-strategist-score-workflow.mjs — regenerate the scoring Workflow from the
 * canonical checklist + the current ledger. This is the repeatable path:
 * when new ideas land in the ledger, regenerate and run the workflow to score
 * them against the SAME stored Strategist Checklist.
 *
 * Workflow scripts cannot read the filesystem, so we embed the checklist + ideas
 * as constants. All prompt text is emitted via JSON.stringify so apostrophes /
 * quotes can never break the (strict) workflow parser.
 *
 *   node scripts/_loop/gen-strategist-score-workflow.mjs            # score ALL ledger ideas
 *   node scripts/_loop/gen-strategist-score-workflow.mjs --new-only # only ideas with no strategist score
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');
const LEDGER = path.join(ROOT, '.loop/biz-opportunities-ledger.json');
const CHECKLIST = path.join(ROOT, 'data/research/strategist-checklist.json');
const OUT = path.join(ROOT, 'scripts/_loop/strategist-score-workflow.js');

const newOnly = process.argv.includes('--new-only');

const checklistFull = JSON.parse(fs.readFileSync(CHECKLIST, 'utf8')).checklist || [];
const compact = checklistFull.map((c) => ({ id: c.id, category: c.category, title: c.title, test: c.test, weight: c.weight }));
const ledger = JSON.parse(fs.readFileSync(LEDGER, 'utf8'));
let ideas = (ledger.opportunities || []).map((i) => ({ key: i.key, name: i.name, one_liner: i.one_liner, category: i.shape || i.category || '', composite: i.composite, _scored: !!i.strategist }));
if (newOnly) ideas = ideas.filter((i) => !i._scored);
ideas = ideas.map(({ _scored, ...rest }) => rest);

// The scoring prompt: structural-fail vs unproven-unknown is the load-bearing distinction.
const PROMPT_HEAD =
  'Score ONE EARLY-STAGE business idea against a strategist-derived business-quality checklist (Tony Robbins, Masters Union founders, Basesh Gala). The idea is described by a one-liner — it is PRE-LAUNCH, so it has no traction, team, or financials yet. Judge the intrinsic potential of the IDEA, not the completeness of its description.\n\nIDEA:\n';
const PROMPT_RULES =
  '\n\nCRITICAL verdict rules — get this distinction right:\n' +
  '- "fail" = the idea is STRUCTURALLY UNABLE to pass: its very nature makes this test impossible to satisfy no matter who executes it. Examples: a newsletter built only on public data structurally has no moat; a thin re-seller structurally has weak unit economics; a business whose whole value evaporates if one regulation changes structurally fails survive-constraint-shifts. A fail must be defensible as "even with perfect execution, this cannot pass."\n' +
  '- "unknown" = the test is simply NOT YET PROVEN or not stated, but a good operator could satisfy it later. Use this for: demand not yet validated, exact margins/CAC/LTV not modeled, team not hired, no metrics yet, distribution not built. Do NOT mark these "fail" — absence of proof in a one-liner is NOT structural impossibility.\n' +
  '- "pass" = the nature of the idea clearly satisfies the test (e.g. a data product that compounds proprietary submissions has a real moat path; a forced-by-deadline regulatory buyer is real demand).\n' +
  '- "partial" = a credible-but-unproven path exists, or it half-meets.\n' +
  'Reserve "fail" for genuine structural defects — those are the real deal-breakers. When in doubt between fail and unknown, choose unknown. One-line reason for every non-pass.\n' +
  'Then: top_strengths (items the nature of the idea nails), top_gaps (the load-bearing weight-2/3 items it STRUCTURALLY fails), and a one-line strategist_verdict (would these strategists back this business, and why or why not).\n' +
  'Judge on merits as described; do not invent capabilities it did not claim, but do not penalize it for detail a one-liner would never include.';

const file = `export const meta = {
  name: 'strategist-score',
  description: 'Score the opportunity ledger against the stored Strategist Checklist (scoring-only; checklist + ideas embedded, regenerated by gen-strategist-score-workflow.mjs)',
  phases: [{ title: 'Score', detail: 'one Sonnet agent per ledger idea vs the checklist' }],
}

const CHECKLIST = ${JSON.stringify(compact)}
const IDEAS = ${JSON.stringify(ideas)}
const PROMPT_HEAD = ${JSON.stringify(PROMPT_HEAD)}
const PROMPT_RULES = ${JSON.stringify(PROMPT_RULES)}

const SCORE_SCHEMA = {
  type: 'object',
  properties: {
    key: { type: 'string' },
    name: { type: 'string' },
    item_verdicts: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          id: { type: 'string' },
          verdict: { type: 'string', enum: ['pass', 'partial', 'fail', 'unknown'] },
          reason: { type: 'string' },
        },
        required: ['id', 'verdict'],
      },
    },
    top_strengths: { type: 'array', items: { type: 'string' } },
    top_gaps: { type: 'array', items: { type: 'string' } },
    strategist_verdict: { type: 'string' },
  },
  required: ['key', 'item_verdicts'],
}

const checklistBlob = JSON.stringify(CHECKLIST)
phase('Score')
log('Scoring ' + IDEAS.length + ' ideas vs ' + CHECKLIST.length + '-item checklist (Sonnet)')
const scored = (await parallel(IDEAS.map((idea) => () =>
  agent(
    PROMPT_HEAD + JSON.stringify(idea) +
    '\\n\\nCHECKLIST (id, category, title, test, weight 1-3):\\n' + checklistBlob +
    PROMPT_RULES + ' key="' + idea.key + '", name="' + idea.name + '".',
    { schema: SCORE_SCHEMA, model: 'sonnet', label: 'score:' + idea.key, phase: 'Score' }
  )
))).filter(Boolean)
log('Scored ' + scored.length + '/' + IDEAS.length)
return { scored }
`;

fs.writeFileSync(OUT, file);
console.log(`Regenerated ${path.relative(ROOT, OUT)}`);
console.log(`  checklist items: ${compact.length}`);
console.log(`  ideas to score: ${ideas.length}${newOnly ? ' (new-only)' : ' (all)'}`);
