#!/usr/bin/env node
/**
 * Generates apps/web/src/lib/festival-clips.ts — the registry of festival
 * page-slugs that have a per-slug, festival-SPECIFIC celebration clip uploaded
 * to the nakshiq-videos R2 bucket as {slug}.mp4 (the de-watermarked Flow/Veo
 * clips from the celebration campaign).
 *
 * Built as the intersection of:
 *   1. the live festival page-slug set (buildFestivalSlugMap over the festivals
 *      table — the EXACT slug the page passes to festivalHeroSrc), and
 *   2. the celebration worklist slug universe (data/festivals/celebration-worklist.json),
 *      so destination / fam- / state- / region- clips can never sneak in, and
 *   3. the actual R2 keys — so the registry can NEVER list a slug whose
 *      <video> would 404.
 *
 * festival-heroes.ts prefers this per-slug clip over the generic real-footage
 * family clip (founder call 2026-06-30: festival-specific wins everywhere).
 *
 * Run with: node --env-file=apps/web/.env.local scripts/_gen-festival-clips.mjs
 */
import { S3Client, ListObjectsV2Command } from "@aws-sdk/client-s3";
import { createClient } from "@supabase/supabase-js";
import { readFileSync, writeFileSync } from "fs";

const env = process.env;

// --- festival page-slug set (mirror of lib/festival-slug.ts) ---
function baseSlug(name) {
  return name.toLowerCase().replace(/[^a-z0-9\s-]+/g, "").trim().replace(/\s+/g, "-").replace(/-+/g, "-");
}
function buildFestivalSlugMap(rows) {
  const baseToCount = new Map();
  for (const r of rows) {
    const b = baseSlug(r.name);
    baseToCount.set(b, (baseToCount.get(b) ?? 0) + 1);
  }
  const idToSlug = new Map();
  for (const r of rows) {
    const b = baseSlug(r.name);
    const slug = (baseToCount.get(b) ?? 1) > 1 && r.destination_id ? `${b}-${r.destination_id}` : b;
    idToSlug.set(r.id, slug);
  }
  return idToSlug;
}

const supabase = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_ANON_KEY);
const { data: rows, error } = await supabase.from("festivals").select("id, name, destination_id");
if (error) { console.error(error); process.exit(1); }
const liveSlugs = new Set(buildFestivalSlugMap(rows).values());
console.log(`Live festival page-slugs: ${liveSlugs.size} (from ${rows.length} festival rows)`);

// --- celebration worklist universe (committed list of per-slug clip slugs) ---
const worklist = JSON.parse(readFileSync("data/festivals/celebration-worklist.json", "utf8"));
const clipUniverse = new Set(worklist.map((w) => w.slug.trim()));
console.log(`Celebration worklist slugs: ${clipUniverse.size}`);

// --- R2 keys ---
const client = new S3Client({
  region: "auto",
  endpoint: `https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
  credentials: { accessKeyId: env.R2_ACCESS_KEY_ID, secretAccessKey: env.R2_SECRET_ACCESS_KEY },
});
const keys = new Set();
let token;
do {
  const r = await client.send(new ListObjectsV2Command({ Bucket: "nakshiq-videos", ContinuationToken: token }));
  for (const o of r.Contents || []) keys.add(o.Key);
  token = r.IsTruncated ? r.NextContinuationToken : undefined;
} while (token);

// --- intersection ---
const withClip = [...liveSlugs].filter((s) => clipUniverse.has(s) && keys.has(`${s}.mp4`)).sort();
console.log(`Festival page-slugs with a per-slug clip in R2: ${withClip.length}/${liveSlugs.size}`);

// diagnostics: worklist slugs that don't match any live festival page-slug
const orphanClips = [...clipUniverse].filter((s) => !liveSlugs.has(s));
if (orphanClips.length) {
  console.log(`\n⚠ ${orphanClips.length} worklist clip-slugs have NO matching live festival page-slug (won't be wired):`);
  console.log(orphanClips.slice(0, 40).map((s) => "  " + s).join("\n"));
}
// worklist slugs that match a live page but are NOT in R2 (should be 0 after sync)
const matchedNotInR2 = [...clipUniverse].filter((s) => liveSlugs.has(s) && !keys.has(`${s}.mp4`));
if (matchedNotInR2.length) {
  console.log(`\n⚠ ${matchedNotInR2.length} matched slugs MISSING from R2 (excluded):`);
  console.log(matchedNotInR2.map((s) => "  " + s).join("\n"));
}

const lines = withClip.map((s) => `  ${JSON.stringify(s)},`).join("\n");
const out = `// AUTO-GENERATED by scripts/_gen-festival-clips.mjs — do not edit by hand.
//
// Registry of /festivals/[festivalSlug] page-slugs that have a per-slug,
// festival-SPECIFIC celebration clip in the nakshiq-videos R2 bucket as
// {slug}.mp4 (the de-watermarked Flow/Veo clips). It is the intersection of
// the live festival page-slug set, the celebration worklist, and the actual
// R2 keys, so every entry is guaranteed to resolve.
//
// festival-heroes.ts prefers this clip over the generic real-footage family
// clip (founder call 2026-06-30: festival-specific clip wins everywhere).
//
// ${withClip.length} festival page-slugs have a per-slug clip.

export const FESTIVAL_CLIPS = new Set<string>([
${lines}
]);
`;

writeFileSync("apps/web/src/lib/festival-clips.ts", out);
console.log(`\nWrote apps/web/src/lib/festival-clips.ts (${withClip.length} slugs)`);
